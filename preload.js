const { contextBridge, ipcRenderer } = require('electron');

contextBridge.exposeInMainWorld('api', {
  getConfig: () => ipcRenderer.invoke('get-config'),
  saveConfig: (cfg) => ipcRenderer.invoke('save-config', cfg),
  getGuilds: () => ipcRenderer.invoke('get-guilds'),
  getServerOverview: () => ipcRenderer.invoke('get-server-overview'),
  leaveOtherServers: () => ipcRenderer.invoke('leave-other-servers'),
  getActivityLogs: () => ipcRenderer.invoke('get-activity-logs'),
  getChannels: (guildId) => ipcRenderer.invoke('get-channels', guildId),
  getVoiceChannels: (guildId) => ipcRenderer.invoke('get-voice-channels', guildId),
  getMembers: (guildId) => ipcRenderer.invoke('get-members', guildId),
  getBots: (guildId) => ipcRenderer.invoke('get-bots', guildId),
  sendMessage: (data) => ipcRenderer.invoke('send-message', data),
  searchGifs: (query) => ipcRenderer.invoke('search-gifs', query),
  sendGif: (data) => ipcRenderer.invoke('send-gif', data),
  sendAnnouncement: (data) => ipcRenderer.invoke('send-announcement', data),
  kickMember: (data) => ipcRenderer.invoke('kick-member', data),
  banMember: (data) => ipcRenderer.invoke('ban-member', data),
  timeoutMember: (data) => ipcRenderer.invoke('timeout-member', data),
  warnMember: (data) => ipcRenderer.invoke('warn-member', data),
  joinVoice: (data) => ipcRenderer.invoke('join-voice', data),
  leaveVoice: (guildId) => ipcRenderer.invoke('leave-voice', guildId),
  playMusic: (data) => ipcRenderer.invoke('play-music', data),
  stopMusic: (guildId) => ipcRenderer.invoke('stop-music', guildId),
  pauseMusic: (guildId) => ipcRenderer.invoke('pause-music', guildId),
  resumeMusic: (guildId) => ipcRenderer.invoke('resume-music', guildId),
  setBotStatus: (text) => ipcRenderer.invoke('set-bot-status', { text }),
  getStats: (guildId) => ipcRenderer.invoke('get-stats', guildId),
  onBotStatus: (cb) => ipcRenderer.on('bot-status', (event, data) => cb(data)),
  onVoiceStatus: (cb) => ipcRenderer.on('voice-status', (event, data) => cb(data)),
  onMusicStatus: (cb) => ipcRenderer.on('music-status', (event, data) => cb(data)),
  onNewMessage: (cb) => ipcRenderer.on('new-message', (event, data) => cb(data)),
  onBotMessage: (cb) => ipcRenderer.on('bot-message', (event, data) => cb(data)),
  onActivityLog: (cb) => ipcRenderer.on('activity-log', (event, data) => cb(data)),
});
